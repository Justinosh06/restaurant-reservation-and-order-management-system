using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using RestaurantReservation.Models;

namespace RestaurantReservation.Models
{
    public enum ReservationStatus
    {
        Pending,
        Confirmed,
        Cancelled,
        Completed
    }

    public enum DepositStatus
    {
        // No deposit asked for, e.g. bookings staff take by phone.
        None,
        // The customer was sent to Stripe and has not paid yet.
        Unpaid,
        Paid,
        Refunded
    }

    public class Reservation : IAutoGeneratedId
    {
        [Key]
        [Required(ErrorMessage = "Reservation ID is required.")]
        public string Id { get; set; } = string.Empty;

        [Required]
        public DateOnly Date { get; set; }

        [Required]
        public TimeOnly TimeSlot { get; set; }

        [Required]
        [Range(1, 20)]
        public int Pax { get; set; }

        public ReservationStatus Status { get; set; } = ReservationStatus.Pending;

        [Required]
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

        // Foreign Keys
        // The tables this booking sits at. Empty until staff assign it on Table Management;
        // a large party can take several tables.
        public List<ReservationTable> ReservationTables { get; set; } = [];

        // Empty for bookings staff take by phone or walk-in; those use the guest fields below.
        public string? CustomerId { get; set; }

        [ForeignKey(nameof(CustomerId))]
        public Customer? Customer { get; set; }

        [StringLength(100)]
        public string? GuestName { get; set; }

        [StringLength(30)]
        public string? ContactNumber { get; set; }

        [StringLength(500)]
        public string? Notes { get; set; }

        // Online bookings pay a deposit through Stripe Checkout. Amount is in sen (2000 = RM20).
        public int? DepositAmount { get; set; }

        public DepositStatus DepositStatus { get; set; } = DepositStatus.None;

        [StringLength(255)]
        public string? StripeSessionId { get; set; }
    }
}