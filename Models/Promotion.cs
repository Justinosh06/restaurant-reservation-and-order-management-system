using System.ComponentModel.DataAnnotations;

namespace RestaurantReservation.Models
{
    public class Promotion : IAutoGeneratedId
    {
        [Key]
        [Required(ErrorMessage = "Promotion ID is required.")]
        public string Id { get; set; } = string.Empty;

        [Required(ErrorMessage = "Title is required.")]
        [StringLength(100, ErrorMessage = "Title cannot exceed 100 characters.")]
        public string Title { get; set; } = string.Empty;

        [Required(ErrorMessage = "Description is required.")]
        [StringLength(1000, ErrorMessage = "Description cannot exceed 1000 characters.")]
        public string Description { get; set; } = string.Empty;

        // The code customers quote for the promotion. Every promotion saved since codes were added has one;
        // older promotions get one the next time they are saved.
        [StringLength(20, MinimumLength = 4, ErrorMessage = "The promo code must be 4 to 20 characters.")]
        [RegularExpression("^[A-Z0-9]+$", ErrorMessage = "The promo code can only use letters and numbers.")]
        public string? Code { get; set; }

        [StringLength(500, ErrorMessage = "Image URL cannot exceed 500 characters.")]
        public string? ImageUrl { get; set; }

        [Required]
        public DateOnly StartDate { get; set; }

        [Required]
        public DateOnly EndDate { get; set; }

        // What the code takes off the bill at checkout. Null for promotions made before discounts were added:
        // their code can't be used until a discount is set.
        public PromotionDiscountType? DiscountType { get; set; }

        // A percentage (1 to 100) for Percentage, or an amount in cents for FixedAmount.
        [Range(0, 10000000)]
        public int DiscountValue { get; set; }

        // The orders total (in cents) the bill must reach before the code can be used; 0 means no minimum.
        [Range(0, 10000000)]
        public int MinimumSpend { get; set; }

        // Who can use the code: anyone, customers signed in to an account, or customers in their birthday month.
        public PromotionAudience Audience { get; set; } = PromotionAudience.Everyone;

        // When customers were emailed about this promotion (UTC); null until it has started and been sent.
        // Set before sending, so a promotion is only ever emailed once, even if it is edited later.
        public DateTime? EmailedAt { get; set; }

        public bool IsRunningOn(DateOnly day) => StartDate <= day && day <= EndDate;

        // The amount (in cents) taken off a bill of subtotal cents, or 0 when the bill doesn't qualify.
        public int DiscountOn(int subtotal)
        {
            if (DiscountType is null || subtotal <= 0 || subtotal < MinimumSpend)
            {
                return 0;
            }

            var discount = DiscountType == PromotionDiscountType.Percentage
                ? (int)Math.Round(subtotal * DiscountValue / 100m, MidpointRounding.AwayFromZero)
                : DiscountValue;
            return Math.Clamp(discount, 0, subtotal);
        }

        // Why this customer can't use the code today, or null when they can.
        // customer is null when the table isn't linked to an account.
        public string? AudienceError(Customer? customer, DateOnly today) => Audience switch
        {
            PromotionAudience.Members when customer is null =>
                $"{Code} is for members only. Log in to your account to use it.",
            PromotionAudience.Birthday when customer is null =>
                $"{Code} is a birthday treat for members. Log in to your account to use it.",
            PromotionAudience.Birthday when customer.DateOfBirth is null =>
                $"{Code} is a birthday treat. Add your date of birth on your profile page to use it.",
            PromotionAudience.Birthday when customer.DateOfBirth.Value.Month != today.Month =>
                $"{Code} can only be used during your birthday month ({customer.DateOfBirth.Value:MMMM}).",
            _ => null
        };
    }

    public enum PromotionDiscountType
    {
        Percentage,
        FixedAmount
    }

    public enum PromotionAudience
    {
        Everyone,
        Members,
        Birthday
    }
}