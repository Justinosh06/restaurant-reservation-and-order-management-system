using System.Linq;
using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using RestaurantReservation.Models;

namespace RestaurantReservation.Data
{
    public class ApplicationDbContext : DbContext
    {
        public ApplicationDbContext(DbContextOptions<ApplicationDbContext> options)
            : base(options)
        {
        }

        // DbSets
        public DbSet<Admin> Admins => Set<Admin>();
        public DbSet<Customer> Customers => Set<Customer>();
        public DbSet<Table> Tables => Set<Table>();
        public DbSet<Reservation> Reservations => Set<Reservation>();
        public DbSet<ReservationTable> ReservationTables => Set<ReservationTable>();
        public DbSet<Session> Sessions => Set<Session>();
        public DbSet<CartItem> CartItems => Set<CartItem>();
        public DbSet<Order> Orders => Set<Order>();
        public DbSet<OrderItem> OrderItems => Set<OrderItem>();
        public DbSet<MenuItem> MenuItems => Set<MenuItem>();
        public DbSet<Transaction> Transactions => Set<Transaction>();
        public DbSet<Feedback> Feedbacks => Set<Feedback>();
        public DbSet<RestaurantSettings> RestaurantSettings => Set<RestaurantSettings>();
        public DbSet<BusinessHours> BusinessHours => Set<BusinessHours>();
        public DbSet<OpeningHoursHistory> OpeningHoursHistory => Set<OpeningHoursHistory>();
        public DbSet<Announcement> Announcements => Set<Announcement>();
        public DbSet<Promotion> Promotions => Set<Promotion>();

        public override int SaveChanges(bool acceptAllChangesOnSuccess)
        {
            AssignMissingStringIds();
            return base.SaveChanges(acceptAllChangesOnSuccess);
        }

        public override Task<int> SaveChangesAsync(
            bool acceptAllChangesOnSuccess,
            CancellationToken cancellationToken = default)
        {
            AssignMissingStringIds();
            return base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);
        }

        protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
        {
            configurationBuilder.Properties<DateTime>().HaveConversion<UtcDateTimeConverter>();
        }

        private void AssignMissingStringIds()
        {
            foreach (var entry in ChangeTracker.Entries<IAutoGeneratedId>()
                         .Where(entry => entry.State == EntityState.Added))
            {
                var primaryKey = entry.Metadata.FindPrimaryKey();
                if (primaryKey is not { Properties.Count: 1 } ||
                    primaryKey.Properties[0].Name != nameof(IAutoGeneratedId.Id) ||
                    primaryKey.Properties[0].ClrType != typeof(string))
                {
                    continue;
                }

                var idProperty = entry.Property(primaryKey.Properties[0].Name);
                if (string.IsNullOrWhiteSpace(idProperty.CurrentValue as string))
                {
                    idProperty.CurrentValue = Guid.NewGuid().ToString("N");
                }
            }
        }

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            base.OnModelCreating(modelBuilder);

            // -------------------------------------------------------------
            // 1. ADMIN
            // -------------------------------------------------------------
            modelBuilder.Entity<Admin>(entity =>
            {
                entity.HasKey(a => a.Id);
                entity.HasIndex(a => a.Email).IsUnique();

                entity.Property(a => a.Role)
                      .HasConversion<string>()
                      .HasMaxLength(20);

                entity.Property(a => a.Gender)
                      .HasConversion<string>()
                      .HasMaxLength(10);
            });

            // -------------------------------------------------------------
            // 2. CUSTOMER
            // -------------------------------------------------------------
            modelBuilder.Entity<Customer>(entity =>
            {
                entity.HasKey(c => c.Id);
                entity.HasIndex(c => c.Email).IsUnique();

                entity.Property(c => c.Gender)
                      .HasConversion<string>()
                      .HasMaxLength(20);
            });

            // -------------------------------------------------------------
            // 3. TABLE
            // -------------------------------------------------------------
            modelBuilder.Entity<Table>(entity =>
            {
                entity.HasKey(t => t.Id);
                entity.Property(t => t.Shape)
                      .HasConversion<string>()
                      .HasMaxLength(20);
            });

            // -------------------------------------------------------------
            // 4. RESERVATION
            // -------------------------------------------------------------
            modelBuilder.Entity<Reservation>(entity =>
            {
                entity.HasKey(r => r.Id);
                entity.Property(r => r.Status)
                      .HasConversion<string>()
                      .HasMaxLength(20);
                entity.Property(r => r.DepositStatus)
                      .HasConversion<string>()
                      .HasMaxLength(20);
                entity.Property(r => r.DepositCurrency)
                      .HasConversion<string>()
                      .HasMaxLength(10);

                // A booking whose deposit is still unpaid is not a real booking yet, so every query
                // skips it. The customer booking page reads them with IgnoreQueryFilters().
                entity.HasQueryFilter(r => r.DepositStatus != DepositStatus.Unpaid);

                entity.HasOne(r => r.Customer)
                      .WithMany()
                      .HasForeignKey(r => r.CustomerId)
                      .OnDelete(DeleteBehavior.Restrict);
            });

            // -------------------------------------------------------------
            // 5. RESERVATION TABLE
            // -------------------------------------------------------------
            modelBuilder.Entity<ReservationTable>(entity =>
            {
                entity.HasKey(rt => rt.Id);

                // Matches the Reservation filter above so links never point at a hidden booking.
                entity.HasQueryFilter(rt => rt.Reservation!.DepositStatus != DepositStatus.Unpaid);

                // Foreign Key to Reservation (a large party can take several tables)
                entity.HasOne(rt => rt.Reservation)
                    .WithMany(r => r.ReservationTables)
                    .HasForeignKey(rt => rt.ReservationId)
                    .OnDelete(DeleteBehavior.Cascade);

                // Foreign Key to Table
                entity.HasOne(rt => rt.Table)
                    .WithMany() // Or .WithMany(t => t.ReservationTables) if navigation collection exists on Table
                    .HasForeignKey(rt => rt.TableId)
                    .OnDelete(DeleteBehavior.Restrict);

                entity.HasIndex(rt => new { rt.ReservationId, rt.TableId })
                    .IsUnique();
            });

            // -------------------------------------------------------------
            // 6. SESSION
            // -------------------------------------------------------------
            modelBuilder.Entity<Session>(entity =>
            {
                entity.HasKey(s => s.Id);
                entity.HasOne(s => s.Table)
                      .WithMany()
                      .HasForeignKey(s => s.TableId)
                      .OnDelete(DeleteBehavior.Restrict);
                entity.HasOne(s => s.Customer)
                      .WithMany()
                      .HasForeignKey(s => s.CustomerId)
                      .OnDelete(DeleteBehavior.Restrict)
                      .IsRequired(false);
                entity.HasOne(s => s.Promotion)
                      .WithMany()
                      .HasForeignKey(s => s.PromotionId)
                      .OnDelete(DeleteBehavior.SetNull)
                      .IsRequired(false);
                entity.HasIndex(s => s.TableId)
                      .IsUnique()
                      .HasFilter("[TableId] IS NOT NULL AND [EndingTime] IS NULL");
            });

            // -------------------------------------------------------------
            // 7. ORDER & ORDERITEM
            // -------------------------------------------------------------
            modelBuilder.Entity<Order>(entity =>
            {
                entity.HasKey(o => o.Id);
                entity.Property(o => o.Status)
                      .HasConversion<string>()
                      .HasMaxLength(20);

                entity.HasOne(o => o.Session)
                      .WithMany(s => s.Orders)
                      .HasForeignKey(o => o.SessionId)
                      .OnDelete(DeleteBehavior.Cascade);

                entity.HasOne(o => o.Customer)
                      .WithMany()
                      .HasForeignKey(o => o.CustomerId)
                      .OnDelete(DeleteBehavior.Restrict)
                      .IsRequired(false);
            });

            modelBuilder.Entity<OrderItem>(entity =>
            {
                entity.HasKey(oi => oi.Id);
                ConfigureOptions(entity.Property(oi => oi.Options));
                entity.HasOne(oi => oi.Order)
                      .WithMany(order => order.OrderItems)
                      .HasForeignKey(oi => oi.OrderId)
                      .OnDelete(DeleteBehavior.Cascade);

                entity.HasOne(oi => oi.MenuItem)
                      .WithMany()
                      .HasForeignKey(oi => oi.MenuItemId)
                      .IsRequired(false)
                      .OnDelete(DeleteBehavior.SetNull);
            });

            // -------------------------------------------------------------
            // 8. MENUITEM
            // -------------------------------------------------------------
            modelBuilder.Entity<MenuItem>(entity =>
            {
                entity.HasKey(m => m.Id);
                entity.Property(m => m.MenuItemType)
                      .HasConversion<string>()
                      .HasMaxLength(30);
                ConfigureOptions(entity.Property(m => m.Options));
            });

            // -------------------------------------------------------------
            // 9. TRANSACTION (Stripe Sandbox Integration)
            // -------------------------------------------------------------
            modelBuilder.Entity<Transaction>(entity =>
            {
                entity.HasKey(t => t.Id);
                entity.Property(t => t.Currency).HasConversion<string>().HasMaxLength(10);
                entity.Property(t => t.Status).HasConversion<string>().HasMaxLength(20);
                entity.Property(t => t.PaymentMethod).HasConversion<string>().HasMaxLength(20);

                entity.HasOne(t => t.Order)
                      .WithMany()
                      .HasForeignKey(t => t.OrderId)
                      .OnDelete(DeleteBehavior.Restrict);
                entity.HasIndex(t => new { t.OrderId, t.StripeCheckoutSessionId })
                      .IsUnique()
                      .HasFilter("[StripeCheckoutSessionId] IS NOT NULL");
            });

            // -------------------------------------------------------------
            // 10. FEEDBACK
            // -------------------------------------------------------------
            modelBuilder.Entity<Feedback>(entity =>
            {
                entity.HasKey(f => f.Id);
                entity.HasOne(f => f.MenuItem)
                      .WithMany()
                      .HasForeignKey(f => f.MenuItemId)
                      .OnDelete(DeleteBehavior.Cascade);

                entity.HasOne(f => f.Customer)
                      .WithMany()
                      .HasForeignKey(f => f.CustomerId)
                      .OnDelete(DeleteBehavior.Restrict);
            });

            // -------------------------------------------------------------
            // 11. RESTAURANT SETTINGS & BUSINESS HOURS
            // -------------------------------------------------------------
            modelBuilder.Entity<RestaurantSettings>(entity =>
            {
                entity.HasKey(s => s.Id);
                entity.Property(s => s.DefaultCurrency)
                      .HasConversion<string>()
                      .HasMaxLength(10);
            });

            modelBuilder.Entity<BusinessHours>(entity =>
            {
                entity.HasKey(b => b.Id);
                entity.Property(b => b.DayOfWeek)
                      .HasConversion<string>()
                      .HasMaxLength(15);

                entity.HasOne(b => b.RestaurantSettings)
                      .WithMany(s => s.BusinessHours)
                      .HasForeignKey(b => b.RestaurantSettingsId)
                      .OnDelete(DeleteBehavior.Cascade);
            });

            modelBuilder.Entity<OpeningHoursHistory>(entity =>
            {
                entity.HasKey(h => h.Id);
                entity.Property(h => h.DayOfWeek)
                      .HasConversion<string>()
                      .HasMaxLength(15);
                entity.HasIndex(h => h.EffectiveFrom);
            });

            // -------------------------------------------------------------
            // 12. ANNOUNCEMENT
            // -------------------------------------------------------------
            modelBuilder.Entity<Announcement>(entity =>
            {
                entity.HasKey(a => a.Id);
            });

            // -------------------------------------------------------------
            // 13. PROMOTION
            // -------------------------------------------------------------
            modelBuilder.Entity<Promotion>(entity =>
            {
                entity.HasKey(p => p.Id);
                entity.Property(p => p.DiscountType)
                      .HasConversion<string>()
                      .HasMaxLength(20);
                entity.HasIndex(p => p.Code)
                      .IsUnique()
                      .HasFilter("[Code] IS NOT NULL");
            });

            // -------------------------------------------------------------
            // 14. CART ITEM
            // -------------------------------------------------------------
            modelBuilder.Entity<CartItem>(entity =>
            {
                entity.HasKey(c => c.Id);
                ConfigureOptions(entity.Property(c => c.Options));

                entity.HasOne(c => c.Session)
                    .WithMany()
                    .HasForeignKey(c => c.SessionId)
                    .OnDelete(DeleteBehavior.Cascade);

                entity.HasOne(c => c.MenuItem)
                    .WithMany()
                    .HasForeignKey(c => c.MenuItemId)
                    .OnDelete(DeleteBehavior.Restrict);
            });

            ConfigureStringPrimaryKeys(modelBuilder);
        }

        private static void ConfigureOptions(PropertyBuilder<Dictionary<string, string>> property)
        {
            property.HasConversion(
                options => SerializeOptions(options),
                json => DeserializeOptions(json));
            property.Metadata.SetValueComparer(new ValueComparer<Dictionary<string, string>>(
                (left, right) => SerializeOptions(left) == SerializeOptions(right),
                options => SerializeOptions(options).GetHashCode(),
                options => DeserializeOptions(SerializeOptions(options))));
        }

        private static string SerializeOptions(Dictionary<string, string> options) =>
            JsonSerializer.Serialize(options);

        private static Dictionary<string, string> DeserializeOptions(string json) =>
            JsonSerializer.Deserialize<Dictionary<string, string>>(json) ?? new();

        private static void ConfigureStringPrimaryKeys(ModelBuilder modelBuilder)
        {
            foreach (var entityType in modelBuilder.Model.GetEntityTypes())
            {
                var primaryKey = entityType.FindPrimaryKey();
                if (primaryKey is not { Properties.Count: 1 } || primaryKey.Properties[0].ClrType != typeof(string))
                {
                    continue;
                }

                modelBuilder.Entity(entityType.ClrType)
                    .Property(primaryKey.Properties[0].Name)
                    .ValueGeneratedNever();
            }
        }
    }
}